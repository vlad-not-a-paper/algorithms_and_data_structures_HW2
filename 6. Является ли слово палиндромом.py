def isPalindrome(s):
    left = 0
    right = len(s) - 1

    while left < right:
        if s[left] != s[right]:
            return False
        left += 1
        right -= 1

    return True

'''
Алгоритм сравнивает символы с начала и с конца, двигая указатели навстречу друг другу. 
Если все пары совпадают, строка является палиндромом. За счёт одного прохода по строке и выполнения не более n/2 сравнений алгоритм работает за линейное время.
'''